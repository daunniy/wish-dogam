def _tm_paren(n):
    m = re.search(r"\(([^()]*)\)\s*$", n)
    if not m: return n
    inner = m.group(1); hits = [c for c in _CHS if c in inner]
    if len(hits) == 1 and len(inner) > 10: return n[:m.start()].rstrip() + f" ({hits[0]})"
    return n

