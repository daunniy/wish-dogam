def fix_name(n):
    if not n: return n
    for a, b in EXACT: n = n.replace(a, b)
    for r, b in RX: n = r.sub(b, n)
    n = re.sub(r"\(\)", "", n)
    return n.strip()

def fix_all(items):
    c = 0
    for i in items:
        nm = fix_name(i.get("name", ""))
        if nm and nm != i.get("name"): i["name"] = nm; c += 1
    return c

